"""Provide one-request MP4 blobs for anonymous pages with an opaque origin."""
import base64
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]

def build():
    scenes=['objects','scene-stairs','scene-steps','scene-slope','scene-maze',
            'accessibility','capability']
    scenes += [prefix+'-'+body for body in ('g1','spot','spot_arm','husky')
               for prefix in ('structure','affordance-traversability','affordance-manipulation')]
    output=ROOT/'assets/loop-videos'
    output.mkdir(exist_ok=True)
    for scene in scenes:
        path=ROOT/'assets/media'/(scene+'.mp4')
        if not path.exists():raise FileNotFoundError(path)
        key=path.relative_to(ROOT).as_posix()
        encoded=base64.b64encode(path.read_bytes()).decode()
        code='''/* Generated by scripts/build_loop_assets.py. Original MP4 bytes. */
(()=>{const cache=window.CLEAR_VIDEO_LOOPS=window.CLEAR_VIDEO_LOOPS||{};
const key=KEY;if(cache[key])return;
const raw=atob(PAYLOAD),bytes=new Uint8Array(raw.length);
for(let i=0;i<raw.length;i++)bytes[i]=raw.charCodeAt(i);
cache[key]=URL.createObjectURL(new Blob([bytes],{type:'video/mp4'}));})();
'''.replace('KEY',json.dumps(key)).replace('PAYLOAD',json.dumps(encoded))
        (output/(scene+'.js')).write_text(code)
    print(f'Built {len(scenes)} cached loop payloads')

if __name__=='__main__':build()
