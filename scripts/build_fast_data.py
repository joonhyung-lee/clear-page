"""Losslessly pack chart/sample JSON for script loading in an opaque sandbox."""
import base64
import gzip
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'learning-samples': 'window.CLEAR_LEARNING_SAMPLES',
    'learning-samples-grounding': 'window.CLEAR_LEARNING_SAMPLES["grounding"]',
    'learning-samples-ordering': 'window.CLEAR_LEARNING_SAMPLES["ordering"]',
    'g1-restored-data': 'window.CLEAR_BODY_CURRICULA["g1"]',
    'spot_arm-restored-data': 'window.CLEAR_BODY_CURRICULA["spot_arm"]',
    'spot-curriculum-data': 'window.CLEAR_BODY_CURRICULA["spot"]',
    'training-loss-data': 'window.CLEAR_TRAINING_LOSSES',
}

def build():
    samples=json.loads((ROOT/'assets/learning-samples.js').read_text().split('=',1)[1].strip().removesuffix(';'))
    metadata={k:v for k,v in samples.items() if k not in ['grounding','ordering']}
    for kind in ['grounding','ordering']:
        target=f'window.CLEAR_LEARNING_SAMPLES["{kind}"]'
        (ROOT/f'assets/learning-samples-{kind}.js').write_text('window.CLEAR_LEARNING_SAMPLES=window.CLEAR_LEARNING_SAMPLES||{};\nObject.assign(window.CLEAR_LEARNING_SAMPLES,'+json.dumps(metadata,separators=(',',':'))+');\n'+target+' = '+json.dumps(samples[kind],separators=(',',':'))+';\n')
    for name, target in SOURCES.items():
        source = ROOT / f'assets/{name}.js'
        original=source.read_text()
        text = original.split(target, 1)[1].lstrip().removeprefix('=').strip().removesuffix(';')
        payload = json.loads(text)
        if name.endswith(('restored-data','curriculum-data')):
            for stage in payload.get('checkpoints',payload.get('stages',[])):
                replay=stage.get('replay')
                if not replay:continue
                video=f"assets/media/{replay['scene']}-update-{replay['cumulativeUpdates']:05d}.mp4"
                if (ROOT/video).is_file():replay['video']=video
            # The plain fallback serves exactly the same checkpoints.
            source.write_text(original.split(target,1)[0]+target+' = '+json.dumps(payload,separators=(',', ':'))+';\n')
        packed = base64.b64encode(gzip.compress(json.dumps(payload, separators=(',', ':')).encode(), mtime=0)).decode()
        path = f'assets/{name}.packed.js'
        code = f'''/* Generated by scripts/build_fast_data.py; original JSON is preserved. */
window.CLEAR_DATA_READY=window.CLEAR_DATA_READY||{{}};
window.CLEAR_DATA_READY[{json.dumps(path)}]=(async()=>{{
const bytes=Uint8Array.from(atob({json.dumps(packed)}),c=>c.charCodeAt(0));
const stream=new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
const data=JSON.parse(await new Response(stream).text());
window.CLEAR_BODY_CURRICULA=window.CLEAR_BODY_CURRICULA||{{}};
window.CLEAR_LEARNING_SAMPLES=window.CLEAR_LEARNING_SAMPLES||{{}};
Object.assign(window.CLEAR_LEARNING_SAMPLES,{json.dumps(metadata if name.startswith('learning-samples-') else {},separators=(',',':'))});
{target}=data;
}})();
'''
        (ROOT/path).write_text(code)
        print(f'{source.name}: {source.stat().st_size:,} → {len(code):,} bytes')

if __name__ == '__main__':
    build()
