"""Build complementary source/checkpoint ZIPs from the audited local snapshot."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import stat
import sys
import zipfile

from code_package_layout import checkpoint_layout, README, RUNS
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'release_tools'))
from refactor import build as refactor_build, TOPS as CODE_TOPS   # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'clear-standalone-anonymous'
OUTPUT = ROOT / 'assets/code-downloads'
# Release bookkeeping that reviewers do not need: audit reports, release tooling,
# result tables and the local dependency freeze. README and the checkpoint path map
# are regenerated below.
EXCLUDE_PREFIXES = ('docs/', 'tools/', 'runtime/outputs/', 'runtime/evaluation/evidence/', 'runtime/paper/',
                    # maze v4 (exp5) is not part of the paper: its module, data and 24 checkpoints stay out
                    'runtime/experiments/exp5_maze_v4/', 'runtime/data/plans/', 'runtime/data/probes/', 'runtime/data/rosters/',
                    'runtime/assets/checkpoints/leap2026/V4/',
                    )
EXCLUDE_FILES = {'LICENSE', 'runtime/LICENSE', '.gitignore', 'requirements-core-linux-py311.txt', 'README.md', 'run.py', 'pyproject.toml',
                 'runtime/tests/test_actual_target_validation.py', 'runtime/LICENSING.md',   # notices live in the README
                 'runtime/experiments/exp1/configs/paper.json'}   # rewritten below with the packaged paths
# Helper packages move under utils/, the ordering baselines under models/; utils/tools/run.py puts both on sys.path.
MOVES = {'tests/': 'utils/tests/', 'viz/': 'utils/viz/', 'training/': 'utils/training/', 'scripts/': 'utils/scripts/',
         'evaluation/': 'utils/evaluation/', 'baselines/': 'models/baselines/'}


# Folders whose Python the refactor drops entirely; their data files are not shipped either.
DROP_DATA_DIRS = ('runtime/clear/mj_util/', 'runtime/clear/low_level/', 'runtime/clear/ego_afford/', 'runtime/clear/model/v4/',
                  'runtime/clear/data/v4/', 'runtime/experiments/exp3/development/', 'runtime/scripts/', 'runtime/evaluation/',
                  'runtime/assets/google_robot/')
RELOCATE = {'runtime/clear/model/quantizers/LICENSE': 'clear/model/QUANTIZERS_LICENSE'}
RELOCATE_PREFIXES = {'runtime/data/probe_scenes/': 'experiments/exp3/data/probe_scenes/',   # probe recordings the exp3/exp4 training reads
                     'runtime/assets/g1_wo_wrist/': 'assets/g1/',                           # the G1 model (the paper's G1 has no wrist joints)
                     'runtime/training/configs/exp3/': 'utils/training/exp3/configs/'}      # one training folder per experiment


def packaged(relative):
    if relative.endswith('.py') and relative.removeprefix('runtime/').split('/')[0] in CODE_TOPS:
        return False   # distributed Python is generated by release_tools/refactor.py
    return relative not in EXCLUDE_FILES and not relative.startswith(EXCLUDE_PREFIXES + DROP_DATA_DIRS)


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def archive_metadata(target):
    with zipfile.ZipFile(target) as archive:
        members = [dict(path=i.filename, bytes=i.file_size,
                        type='symlink' if stat.S_ISLNK(i.external_attr >> 16) else 'file')
                   for i in archive.infolist() if not i.is_dir()]
    return dict(url='../assets/code-downloads/'+target.name, bytes=target.stat().st_size,
                sha256=digest(target), files=len(members), members=members)


def main(index_only=False, source_only=False):
    audit = json.loads((PACKAGE / 'docs/tree_audit.json').read_text())
    if audit['status'] != 'passed':
        raise ValueError('Anonymous snapshot audit must pass before packaging')
    OUTPUT.mkdir(parents=True, exist_ok=True)
    # The distribution is flat: runtime/ becomes the root and checkpoints live in ckpts/.
    layout = {old: dict(path='ckpts/' + item['path'].removeprefix('checkpoints/'), sha256=item['sha256'])
              for old, item in checkpoint_layout(PACKAGE, audit).items() if packaged(old)}
    paths = {old.removeprefix('runtime/'): item for old, item in layout.items()}
    templates = ROOT / 'release_tools/templates'
    extras = {
        'README.md': README.encode(),
        'ckpts/paths.json': (json.dumps({'schema': 'clear-checkpoint-paths-v1', 'models': paths}, indent=2)+'\n').encode(),
        'utils/tools/link_checkpoints.py': (templates / 'link_checkpoints.py').read_bytes(),
        'utils/tools/fetch_checkpoints.py': (templates / 'fetch_checkpoints.py').read_bytes(),
        'utils/tools/render_plan.py': (templates / 'render_plan.py').read_bytes(),
        'utils/tools/run.py': (templates / 'run.py').read_bytes(),
        'utils/tests/conftest.py': (templates / 'conftest.py').read_bytes(),
        'utils/training/exp2/train_defaults.json': (templates / 'exp2_train_defaults.json').read_bytes(),
        'utils/tools/get.py': (templates / 'get.py').read_bytes(),
        'pyproject.toml': (templates / 'pyproject.toml').read_bytes(),
    }
    for image in sorted((templates / 'teasers').glob('*.png')):
        extras['assets/' + image.name] = image.read_bytes()
    for index, (name, doc, stages) in enumerate(RUNS, 1):
        file = f'run_{index:02d}_{name}.py'
        if stages is None:
            extras[file] = (templates / file).read_bytes()
            continue
        table = ''.join(f'    {stage!r}: {spec!r},\n' for stage, spec in stages.items())
        extras[file] = f'"""{doc}"""\nfrom utils.tools.run import main\n\nmain({{\n{table}}})\n'.encode()
    def destination(relative):
        if relative in layout:
            return layout[relative]['path']
        if relative in RELOCATE:
            return RELOCATE[relative]
        for old, new in RELOCATE_PREFIXES.items():
            if relative.startswith(old):
                return new + relative.removeprefix(old)
        relative = relative.removeprefix('runtime/')
        for old, new in MOVES.items():
            if relative.startswith(old):
                return new + relative.removeprefix(old)
        return relative

    # Distributed Python: the refactored tree (release_tools/refactor.py), placed by destination().
    for rel, text in refactor_build(PACKAGE / 'runtime').items():
        extras[destination('runtime/' + rel)] = text.encode()
    # The exp1 release freeze pins the source it was evaluated with; the distribution re-pins every
    # shipped Python file, so `run_01_grid.py evaluate` verifies exactly this tree.
    freeze = json.loads((PACKAGE / 'runtime/experiments/exp1/configs/paper.json').read_text())
    freeze['code_sha256'] = {rel: hashlib.sha256(data).hexdigest() for rel, data in sorted(extras.items())
                             if rel.endswith('.py') and rel.split('/')[0] in ('clear', 'experiments', 'models', 'utils')}
    freeze['packaging_note'] += (' Distribution tree (2026-10-15): the physical-execution stack, maze v4 and unreached modules are '
                                 'removed and small modules are merged (release_tools/refactor.py); code_sha256 pins the shipped files.')
    extras['experiments/exp1/configs/paper.json'] = (json.dumps(freeze, indent=2) + '\n').encode()

    result = {}
    for key, name in [('source', 'clear-source.zip'), ('checkpoints', 'clear-pretrained.zip')]:
        entries = [(p, row) for p, row in audit['scanned_files'].items()
                   if (Path(p).suffix == '.pt') == (key == 'checkpoints') and packaged(p)]
        target = OUTPUT / name
        if index_only or (source_only and key == 'checkpoints'):
            result[key] = archive_metadata(target)
            continue
        temporary = target.with_suffix('.zip.partial')
        with zipfile.ZipFile(temporary, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=1) as archive:
            for i, (relative, row) in enumerate(entries):
                path = PACKAGE / relative
                info = zipfile.ZipInfo('clear/' + destination(relative))
                info.create_system = 3
                info.compress_type = zipfile.ZIP_DEFLATED
                info._compresslevel = 1
                if 'symlink' in row:
                    assert path.is_symlink() and str(path.readlink()) == row['symlink']
                    assert path.resolve().is_relative_to(PACKAGE) and path.exists()
                    info.external_attr = (stat.S_IFLNK | 0o777) << 16
                    archive.writestr(info, row['symlink'].encode())
                else:
                    if digest(path) != row['sha256']:
                        raise ValueError('Snapshot changed after its audit: ' + relative)
                    info.external_attr = (stat.S_IFREG | 0o644) << 16
                    with path.open('rb') as src, archive.open(info, 'w', force_zip64=True) as dst:
                        shutil.copyfileobj(src, dst, length=1024*1024)
                if (i+1) % 50 == 0:
                    print(f'{key}: {i+1}/{len(entries)} files', flush=True)
            if key == 'source':
                for relative, payload in extras.items():
                    info = zipfile.ZipInfo('clear/' + relative)
                    info.create_system = 3
                    info.compress_type = zipfile.ZIP_DEFLATED
                    info.external_attr = (stat.S_IFREG | 0o644) << 16
                    archive.writestr(info, payload)
        # Check the bytes stored inside each archive, including symlink targets.
        with zipfile.ZipFile(temporary) as archive:
            for relative, row in entries:
                with archive.open('clear/' + destination(relative)) as stream:
                    actual = hashlib.file_digest(stream, 'sha256').hexdigest()
                expected = row.get('sha256') or hashlib.sha256(row['symlink'].encode()).hexdigest()
                if actual != expected:
                    raise ValueError('Archive member changed: ' + relative)
            if key == 'source':
                for relative, payload in extras.items():
                    if archive.read('clear/' + relative) != payload:
                        raise ValueError('Generated package file changed: ' + relative)
        temporary.replace(target)
        result[key] = archive_metadata(target)
        print(f'{key}: archive verified', flush=True)
    (ROOT / 'assets/code-archives.js').write_text('window.CLEAR_CODE_ARCHIVES='+json.dumps(result,separators=(',', ':'))+';\n')
    print(json.dumps({key: {k: v for k, v in row.items() if k != 'members'} for key, row in result.items()}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--index-only', action='store_true', help='Read existing ZIP contents without rebuilding archives')
    parser.add_argument('--source-only', action='store_true', help='Rebuild the source ZIP; index the existing checkpoint ZIP')
    arguments = parser.parse_args()
    main(arguments.index_only, arguments.source_only)
